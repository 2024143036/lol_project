"""Plot lane-by-lane blue/red predicted TCI at 5-minute cumulative checkpoints.

Requires datasets from prepare_tci_targets_gold_level_v2.py and models from
train_tci_models.py. Chart shows MODEL-PREDICTED y_tci in standardized units,
not a calibrated 0-100 score or a win probability.

Examples:
  python plot_tci_5min.py
  python plot_tci_5min.py --match-id KR_7461530602
  python plot_tci_5min.py --split test --list-matches
  python plot_tci_5min.py --split all --match-id KR_7461530602
"""
import argparse
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

LANES = ('top', 'jungle', 'middle', 'bottom')
PARTS = ('train', 'val', 'test')


def path_under_root(root, spec):
    p = Path(spec)
    return p if p.is_absolute() else root / p


def load_lane(lane, data_dir, model_dir, split):
    parts = PARTS if split == 'all' else (split,)
    chunks = []
    for part in parts:
        path = data_dir / f'{lane}_{part}.csv'
        if not path.is_file():
            raise FileNotFoundError(f'Missing {path}. Run prepare_tci_targets_gold_level_v2.py first.')
        chunk = pd.read_csv(path, dtype={'matchId': str})
        chunk['data_split'] = part
        chunks.append(chunk)
    df = pd.concat(chunks, ignore_index=True)
    model_path = model_dir / f'{lane}_best_model.joblib'
    if not model_path.is_file():
        raise FileNotFoundError(f'Missing {model_path}. Run train_tci_models.py first.')
    bundle = joblib.load(model_path)  # Only load trusted joblib files generated by your own script.
    if not isinstance(bundle, dict) or not {'pipeline', 'features', 'model_name'}.issubset(bundle):
        raise ValueError(f'{lane}: unexpected model bundle format')
    features = bundle['features']
    if any(any(v in col.lower() for v in ('gold', 'level', 'xp')) for col in features):
        raise ValueError(f'{lane}: target leakage feature detected')
    missing = set(features) - set(df.columns)
    if missing:
        raise ValueError(f'{lane}: missing model input columns: {sorted(missing)}')
    required = ['matchId', 'minute', 'side', 'y_tci', 'win']
    if any(k not in df for k in required):
        raise ValueError(f'{lane}: data missing required columns')
    if df.duplicated(['matchId', 'minute', 'side']).any():
        raise ValueError(f'{lane}: duplicated matchId/minute/side records')
    if df.empty:
        raise ValueError(f'{lane}: empty dataset')
    if (df['minute'] % 5 != 0).any():
        raise ValueError(f'{lane}: not all records use 5-minute checkpoints')
    X = df[features].apply(pd.to_numeric, errors='coerce')
    if X.isna().all().any():
        raise ValueError(f'{lane}: model input feature entirely missing')
    df['predicted_tci'] = bundle['pipeline'].predict(X)
    if not np.isfinite(df['predicted_tci']).all():
        raise ValueError(f'{lane}: predicted TCI has invalid values')
    df['lane'] = lane.upper()
    df['model_name'] = bundle['model_name']
    return df


def draw_match(df, output_dir, match_id):
    match = df[df['matchId'] == match_id].copy()
    if match.empty:
        raise ValueError(f'Match ID not found: {match_id}')
    fig, axes = plt.subplots(2, 2, figsize=(14, 9), sharex=True)
    palette = {'blue': '#2468b4', 'red': '#d84d54'}
    for ax, lane in zip(axes.flat, LANES):
        sub = match[match['lane'] == lane.upper()].copy()
        if sub.empty:
            ax.set_title(f'{lane.upper()} (no data)')
            continue
        for side in ('blue', 'red'):
            curve = sub[sub['side'] == side].sort_values('minute')
            if not curve.empty:
                ax.plot(curve['minute'], curve['predicted_tci'], 'o-',
                        label=side.title(), color=palette[side], linewidth=2)
        ax.axhline(0, color='gray', linewidth=0.9, linestyle='--', alpha=0.7)
        ax.set_title(f'{lane.upper()} | {sub["model_name"].iloc[0]}')
        ax.set_ylabel('Predicted TCI (standardized units)')
        ax.set_xlabel('Game time (minutes)')
        ax.grid(alpha=0.25)
        ax.legend(loc='best')
        ax.set_xticks(sorted(sub['minute'].unique()))
    splits = sorted(match['data_split'].unique())
    fig.suptitle(f'5-minute cumulative TCI, match {match_id}  |  split: {", ".join(splits)}',
                 fontsize=15, fontweight='bold')
    fig.text(0.5, 0.012,
             'Line values are model predictions for each side, not win probability. '
             'Do not compare raw magnitudes across lanes.',
             ha='center', fontsize=9, color='dimgray')
    fig.tight_layout(rect=[0, 0.035, 1, 0.95])
    image_path = output_dir / f'tci_5min_{match_id}.png'
    fig.savefig(image_path, dpi=170, bbox_inches='tight')
    plt.close(fig)

    order = ['matchId', 'data_split', 'lane', 'side', 'minute', 'win', 'model_name',
             'y_tci', 'predicted_tci']
    csv_path = output_dir / f'tci_5min_{match_id}.csv'
    match[order].sort_values(['lane', 'minute', 'side']).to_csv(
        csv_path, index=False, encoding='utf-8-sig')
    # Additional figure: actual supervised target vs model prediction.
    comparison_path = output_dir / f'tci_actual_vs_pred_{match_id}.png'
    fig2, axes2 = plt.subplots(2, 2, figsize=(15, 9), sharex=True)
    for ax, lane in zip(axes2.flat, LANES):
        sub = match[match['lane'] == lane.upper()].copy()
        if sub.empty:
            ax.set_title(f'{lane.upper()} (no data)')
            continue
        for side in ('blue', 'red'):
            curve = sub[sub['side'] == side].sort_values('minute')
            if curve.empty:
                continue
            actual = pd.to_numeric(curve['y_tci'], errors='coerce')
            predicted = pd.to_numeric(curve['predicted_tci'], errors='coerce')
            if not np.isfinite(actual).all() or not np.isfinite(predicted).all():
                raise ValueError(f'{match_id} / {lane} / {side}: invalid actual or predicted values')
            ax.plot(curve['minute'], actual, 'o-', color=palette[side],
                    linewidth=2.1, label=f'{side.title()} actual')
            ax.plot(curve['minute'], predicted, 's--', color=palette[side],
                    linewidth=1.8, alpha=0.85, label=f'{side.title()} predicted')
        errors = pd.to_numeric(sub['y_tci'], errors='coerce') - pd.to_numeric(sub['predicted_tci'], errors='coerce')
        rmse = float(np.sqrt(np.mean(np.square(errors))))
        mae = float(np.mean(np.abs(errors)))
        ax.axhline(0, color='gray', linewidth=0.9, linestyle=':', alpha=0.7)
        ax.set_title(f'{lane.upper()} | {sub["model_name"].iloc[0]} | RMSE {rmse:.3f}, MAE {mae:.3f}')
        ax.set_ylabel('TCI (standardized units)')
        ax.set_xlabel('Game time (minutes)')
        ax.grid(alpha=0.25)
        ax.legend(loc='best', fontsize=8, ncol=2)
        ax.set_xticks(sorted(sub['minute'].unique()))
    fig2.suptitle(f'Actual vs predicted TCI | match {match_id} | split: {", ".join(splits)}',
                  fontsize=15, fontweight='bold')
    fig2.text(0.5, 0.012,
              'Solid = actual target (gold + level gap); dashed = model prediction. '
              'Blue / red are opposite sides. RMSE and MAE are for this match only.',
              ha='center', fontsize=9, color='dimgray')
    fig2.tight_layout(rect=[0, 0.035, 1, 0.95])
    fig2.savefig(comparison_path, dpi=170, bbox_inches='tight')
    plt.close(fig2)
    return image_path, comparison_path, csv_path


def main():
    parser = argparse.ArgumentParser(description='Plot 5-minute cumulative TCI for all four lanes')
    parser.add_argument('--data-dir', default='tci_supervised')
    parser.add_argument('--model-dir', default='tci_model_results')
    parser.add_argument('--output-dir', default='tci_timeline_charts')
    parser.add_argument('--split', choices=['train', 'val', 'test', 'all'], default='test',
                        help='Default test. For a specific match from train/val use --split all.')
    parser.add_argument('--match-id', default=None, help='Specific matchId to plot')
    parser.add_argument('--list-matches', action='store_true', help='Show available match IDs')
    parser.add_argument('--all-matches', action='store_true', help='Save charts for every available match')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    data_dir = path_under_root(root, args.data_dir)
    model_dir = path_under_root(root, args.model_dir)
    output_dir = path_under_root(root, args.output_dir)
    datasets = [load_lane(lane, data_dir, model_dir, args.split) for lane in LANES]
    df = pd.concat(datasets, ignore_index=True)
    by_lane = [set(x['matchId']) for x in datasets]
    matches = sorted(set.intersection(*by_lane))
    if not matches:
        raise ValueError('No shared matchId across four lanes')
    if args.list_matches:
        print(f'Available matchIds for split={args.split} ({len(matches)}):')
        for mid in matches:
            print('  ' + mid)
        return
    if args.match_id and args.match_id not in matches:
        raise ValueError(f'{args.match_id} not available in split={args.split}. '
                         f'Use --list-matches or --split all.')
    selected = matches if args.all_matches else [args.match_id or matches[0]]
    output_dir.mkdir(parents=True, exist_ok=True)
    for mid in selected:
        img, comparison, csv = draw_match(df, output_dir, mid)
        print(f'Match: {mid} | image: {img.name} | actual-vs-pred: {comparison.name} | CSV: {csv.name}')
    print(f'Done: {len(selected)} match(es), output: {output_dir}')
    if args.split != 'test':
        print('NOTE: train/val plots are development diagnostics, not unbiased model evaluations.')
    print('TCI values are standardized continuous predictions, NOT 0-100 scores.')


if __name__ == '__main__':
    main()
